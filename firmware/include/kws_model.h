// Hàm suy luận mạng nơ-ron TinyKWS trực tiếp trên ESP32-S3
// Đầu vào: ma trận MFCC [99 frames x 13 coeffs] = 1,287 float
// Đầu ra: mảng xác suất 10 lớp [NUM_CLASSES]
inline void kws_run_inference(const float* mfcc_in, float* out_probs) {
    // Kích thước các lớp trung gian
    // pool1: 16 x 49 x 6
    // pool2: 32 x 24 x 3
    // pool3: 64 x 12 x 1
    static float pool1[16 * 49 * 6];
    float* pool2 = pool1; // Tái sử dụng bộ nhớ pool1 (2304 floats <= 4704 floats)
    float* pool3 = pool1; // Tái sử dụng bộ nhớ pool1 (768 floats <= 4704 floats)
    static float dw_buf[32 * 49 * 6];

    // 1. Conv1 (1 -> 16, 3x3 pad 1) + ReLU + MaxPool(2,2)
    for (int oc = 0; oc < 16; oc++) {
        const float* w_k = &w_c1[oc * 9];
        float bias = b_c1[oc];
        for (int pi = 0; pi < 49; pi++) {
            int i0 = pi * 2;
            for (int pj = 0; pj < 6; pj++) {
                int j0 = pj * 2;
                float max_val = -1e9f;
                for (int di = 0; di < 2; di++) {
                    int r = i0 + di;
                    for (int dj = 0; dj < 2; dj++) {
                        int c = j0 + dj;
                        float sum = bias;
                        for (int ki = 0; ki < 3; ki++) {
                            int in_r = r + ki - 1;
                            if (in_r >= 0 && in_r < 99) {
                                for (int kj = 0; kj < 3; kj++) {
                                    int in_c = c + kj - 1;
                                    if (in_c >= 0 && in_c < 13) {
                                        float in_val = mfcc_in[in_r * 13 + in_c];
                                        sum += in_val * w_k[ki * 3 + kj];
                                    }
                                }
                            }
                        }
                        if (sum < 0.0f) sum = 0.0f; // ReLU
                        if (sum > max_val) max_val = sum;
                    }
                }
                pool1[(oc * 49 + pi) * 6 + pj] = max_val;
            }
        }
    }

    // 2. Block 2: DW2 (16 ch, 3x3 pad 1)
    for (int c = 0; c < 16; c++) {
        const float* w_k = &w_dw2[c * 9];
        float bias = b_dw2[c];
        for (int i = 0; i < 49; i++) {
            for (int j = 0; j < 6; j++) {
                float sum = bias;
                for (int ki = 0; ki < 3; ki++) {
                    int in_r = i + ki - 1;
                    if (in_r >= 0 && in_r < 49) {
                        for (int kj = 0; kj < 3; kj++) {
                            int in_c = j + kj - 1;
                            if (in_c >= 0 && in_c < 6) {
                                sum += pool1[(c * 49 + in_r) * 6 + in_c] * w_k[ki * 3 + kj];
                            }
                        }
                    }
                }
                dw_buf[(c * 49 + i) * 6 + j] = sum;
            }
        }
    }

    // PW2 (16 -> 32, 1x1) + ReLU + MaxPool(2,2)
    for (int oc = 0; oc < 32; oc++) {
        float bias = b_pw2[oc];
        const float* pw_weights = &w_pw2[oc * 16];
        for (int pi = 0; pi < 24; pi++) {
            int i0 = pi * 2;
            for (int pj = 0; pj < 3; pj++) {
                int j0 = pj * 2;
                float max_val = -1e9f;
                for (int di = 0; di < 2; di++) {
                    int r = i0 + di;
                    for (int dj = 0; dj < 2; dj++) {
                        int c = j0 + dj;
                        float sum = bias;
                        for (int ic = 0; ic < 16; ic++) {
                            sum += dw_buf[(ic * 49 + r) * 6 + c] * pw_weights[ic];
                        }
                        if (sum < 0.0f) sum = 0.0f; // ReLU
                        if (sum > max_val) max_val = sum;
                    }
                }
                pool2[(oc * 24 + pi) * 3 + pj] = max_val;
            }
        }
    }

    // 3. Block 3: DW3 (32 ch, 3x3 pad 1)
    for (int c = 0; c < 32; c++) {
        const float* w_k = &w_dw3[c * 9];
        float bias = b_dw3[c];
        for (int i = 0; i < 24; i++) {
            for (int j = 0; j < 3; j++) {
                float sum = bias;
                for (int ki = 0; ki < 3; ki++) {
                    int in_r = i + ki - 1;
                    if (in_r >= 0 && in_r < 24) {
                        for (int kj = 0; kj < 3; kj++) {
                            int in_c = j + kj - 1;
                            if (in_c >= 0 && in_c < 3) {
                                sum += pool2[(c * 24 + in_r) * 3 + in_c] * w_k[ki * 3 + kj];
                            }
                        }
                    }
                }
                dw_buf[(c * 24 + i) * 3 + j] = sum;
            }
        }
    }

    // PW3 (32 -> 64, 1x1) + ReLU + MaxPool(2,2)
    for (int oc = 0; oc < 64; oc++) {
        float bias = b_pw3[oc];
        const float* pw_weights = &w_pw3[oc * 32];
        for (int pi = 0; pi < 12; pi++) {
            int i0 = pi * 2;
            for (int pj = 0; pj < 1; pj++) {
                int j0 = pj * 2;
                float max_val = -1e9f;
                for (int di = 0; di < 2; di++) {
                    int r = i0 + di;
                    for (int dj = 0; dj < 2; dj++) {
                        int c = j0 + dj;
                        if (c >= 3) continue;
                        float sum = bias;
                        for (int ic = 0; ic < 32; ic++) {
                            sum += dw_buf[(ic * 24 + r) * 3 + c] * pw_weights[ic];
                        }
                        if (sum < 0.0f) sum = 0.0f; // ReLU
                        if (sum > max_val) max_val = sum;
                    }
                }
                pool3[oc * 12 + pi] = max_val;
            }
        }
    }

    // 4. Global Average Pooling (64 ch x 12 -> 64)
    float gap[64];
    for (int c = 0; c < 64; c++) {
        float sum = 0.0f;
        for (int i = 0; i < 12; i++) {
            sum += pool3[c * 12 + i];
        }
        gap[c] = sum / 12.0f;
    }

    // 5. Fully Connected (64 -> NUM_CLASSES) + Softmax
    float logits[NUM_CLASSES];
    float max_logit = -1e9f;
    for (int k = 0; k < NUM_CLASSES; k++) {
        float sum = b_fc[k];
        const float* fc_row = &w_fc[k * 64];
        for (int c = 0; c < 64; c++) {
            sum += gap[c] * fc_row[c];
        }
        logits[k] = sum;
        if (sum > max_logit) max_logit = sum;
    }

    float sum_exp = 0.0f;
    for (int k = 0; k < NUM_CLASSES; k++) {
        out_probs[k] = expf(logits[k] - max_logit);
        sum_exp += out_probs[k];
    }
    for (int k = 0; k < NUM_CLASSES; k++) {
        out_probs[k] /= sum_exp;
    }
}

